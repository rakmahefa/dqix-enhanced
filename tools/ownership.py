"""Declare who owns each path, and check the tree against that declaration.

M5's ownership map: every tracked path belongs to exactly one category.

  upstream        consumed from the base project; edits must be additive,
                  marked and listed here (or moved to `shared`)
  shared          a base-project file this fork edits on purpose; the only
                  files allowed to conflict during an upstream sync
  fork            this fork's own files; upstream has no equivalent
  deleted-upstream  deliberately removed; must never come back

The rules are ordered: the first pattern that matches a path wins, so the
most specific rule is written first. `python3 tools/ownership.py` checks that
every tracked path is covered and that a deleted path is absent;
`python3 tools/ownership.py --write` regenerates docs/OWNERSHIP.md.
"""

