def match(path: str, pattern: str) -> bool:
    """Match a repo path against a pattern where `**` spans directories."""
    return _match(path.split("/"), pattern.split("/"))


def _match(parts: list[str], pattern: list[str]) -> bool:
    if not pattern:
        return not parts
    head, rest = pattern[0], pattern[1:]
    if head == "**":
        for index in range(len(parts) + 1):
            if _match(parts[index:], rest):
                return True
        return False
    if not parts:
        return False
    if not _segment_match(parts[0], head):
        return False
    return _match(parts[1:], rest)


def _segment_match(value: str, pattern: str) -> bool:
    if pattern == "*":
        return True
    if "*" not in pattern:
        return value == pattern
    prefix, suffix = pattern.split("*", 1)
    if not value.startswith(prefix) or not value.endswith(suffix):
        return False
    return len(value) >= len(prefix) + len(suffix)


def tracked_paths() -> list[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True, text=True
    )
    return sorted(item for item in result.stdout.split("\0") if item)


def classify(path: str) -> tuple[str, str] | None:
    for pattern, category, note in RULES:
        if match(path, pattern):
            return category, pattern
    return None


def check(paths: list[str]) -> list[str]:
    problems: list[str] = []
    seen_patterns = [pattern for pattern, _, _ in RULES]
    duplicates = [pattern for pattern, count in Counter(seen_patterns).items() if count > 1]
    if duplicates:
        problems.append(f"duplicate rules: {sorted(duplicates)}")
    for pattern, category, _ in RULES:
        if category not in CATEGORIES:
            problems.append(f"unknown category {category!r} for {pattern!r}")
    for path in paths:
        if classify(path) is None:
            problems.append(f"no ownership rule covers {path}")
    for path in paths:
        if classify(path) and classify(path)[0] == "deleted-upstream":  # type: ignore[index]
            problems.append(f"deliberately deleted upstream path is back: {path}")
    if not (ROOT / "docs/OWNERSHIP.md").is_file():
        problems.append("docs/OWNERSHIP.md is missing; run tools/ownership.py --write")
    return problems


def render(paths: list[str]) -> str:
    counts = Counter(classify(path)[0] for path in paths if classify(path))  # type: ignore[index]
    lines = [
        "# Ownership map",
        "",
        "This is the M5 answer to \"is this ours?\". Every tracked path belongs to",
        "exactly one category, declared in `tools/ownership.py` and checked by",
        "`tests/packaging/test_upstream_policy.py`. Generated by",
        "`python3 tools/ownership.py --write`; edit the rules, not this file.",
        "",
        "| Category | Meaning | Paths |",
        "|---|---|---|",
        f"| `upstream` | consumed from the base project; edits must be additive, marked and listed here | {counts.get('upstream', 0)} |",
        f"| `shared` | base-project file this fork edits on purpose — the only files allowed to conflict in a sync | {counts.get('shared', 0)} |",
        f"| `fork` | this fork's own file; upstream has no equivalent | {counts.get('fork', 0)} |",
        f"| `deleted-upstream` | deliberately removed and must stay removed | {counts.get('deleted-upstream', 0)} tracked (none, by design; see below) |",
        f"| **total** | | **{sum(counts.values())}** |",
        "",
        "## Rules",
        "",
        "Rules are ordered; the first pattern that matches a path decides. A path",
        "with no match fails the check, as does a deleted path that returns.",
        "",
        "| Pattern | Category | Why |",
        "|---|---|---|",
    ]
    for pattern, category, note in RULES:
        lines.append(f"| `{pattern}` | `{category}` | {note} |")
    lines += [
        "",
        "## Deliberately deleted upstream",
        "",
        "These paths are recorded so the policy check can fail if they return:",
        "",
    ]
    lines += [
        f"- `{pattern}` — {note}"
        for pattern, category, note in RULES
        if category == "deleted-upstream"
    ]
    lines += [
        "",
        "## The conflict set",
        "",
        "Only `shared` paths may conflict during an upstream sync. A conflict in",
        "an `upstream` path is a design bug: move the change into a fork file, a",
        "wrapper target or a hook, or move the path to `shared` with its reason.",
        "The `deleted-upstream` rules keep the M1 cleanup from being undone.",
        "",
        "## Using the map",
        "",
        "- A bug report or a port cites the path's category before touching it.",
        "- A new fork file gets a rule in the same change, or the check fails.",
        "- `docs/UPSTREAM-SYNC.md` follows this map during the merge drill.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate docs/OWNERSHIP.md")
    args = parser.parse_args()

    paths = tracked_paths()
    if args.write:
        DOC.write_text(render(paths), encoding="utf-8")
        print(f"ownership: wrote {DOC.relative_to(ROOT)} ({len(paths)} tracked paths)")

    problems = check(paths)
    if problems:
        for problem in problems:
            print(f"ownership: {problem}", file=sys.stderr)
        return 1
    counts = Counter(classify(path)[0] for path in paths if classify(path))  # type: ignore[index]
    print(
        "ownership: ok — "
        + ", ".join(f"{counts[category]} {category}" for category in CATEGORIES)
        + f", {len(paths)} tracked paths"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
