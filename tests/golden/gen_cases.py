#!/usr/bin/env python3
"""Generate per-case settings.ini and input.txt from tests/golden/corpus.json."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "corpus.json"
CASES_DIR = HERE / "cases"


def load_manifest():
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def settings_ini(case, manifest):
    lines = ["# Generated by tests/golden/gen_cases.py - do not edit by hand."]
    settings = dict(manifest.get("settings_defaults", {}))
    settings.update(case.get("settings", {}))
    for key, value in settings.items():
        ini_key = manifest["option_to_key"].get(key, key)
        lines.append(f"{ini_key} = {value}")
    return "\n".join(lines) + "\n"


def main():
    manifest = load_manifest()
    CASES_DIR.mkdir(parents=True, exist_ok=True)
    for case in manifest["cases"]:
        cdir = CASES_DIR / case["id"]
        cdir.mkdir(parents=True, exist_ok=True)
        (cdir / "settings.ini").write_text(settings_ini(case, manifest), encoding="utf-8")
        (cdir / "input.txt").write_text(case.get("input", "") or "", encoding="utf-8")
        (cdir / "frames").mkdir(exist_ok=True)
        (cdir / "README.txt").write_text(
            f"{case['id']}: {case['description']}\n"
            f"frames: {case.get('frames', manifest['default_frames'])}\n"
            f"tags: {', '.join(case.get('tags', []))}\n",
            encoding="utf-8",
        )
    print(f"generated {len(manifest['cases'])} cases in {CASES_DIR}")


if __name__ == "__main__":
    main()
